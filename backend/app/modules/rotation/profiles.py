"""Rotation profiles for every playable specialization.

These are concise, production-shaped reference rotations authored from
established endgame priorities (single-target, AoE, opener, movement, and
defensives). They are intentionally data-only so the advisor never special-
cases a class: talent/gear/trinket awareness is expressed via fields, not
branches. Spell ids are included where stable for gear cross-referencing.

This is seed data; a live build would hydrate ``expected_talents`` and
``trinket_guidance`` from talent-tree exports, but the structure is final.
"""

